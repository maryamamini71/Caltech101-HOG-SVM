import os
import numpy as np
import matplotlib.pyplot as plt
import plotly.graph_objects as go

from PIL import Image
from skimage.feature import hog

from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.metrics import accuracy_score
from sklearn.decomposition import PCA

path = "/content/caltech101/dataset/101_ObjectCategories"

images = []
features = []
hog_images = []
labels = []

print("\n======================================")
print("LOADING DATASET")
print("======================================")

for class_name in sorted(os.listdir(path)):

    class_path = os.path.join(
        path,
        class_name
    )

    if not os.path.isdir(class_path):
        continue

    if class_name == "BACKGROUND_Google":
        continue

    print(
        "Processing class:",
        class_name
    )

    for file_name in os.listdir(class_path):

        file_path = os.path.join(
            class_path,
            file_name
        )

        with Image.open(file_path) as img:

            image = img.convert("L")

            image = image.resize(
                (64, 64)
            )

            image = np.array(image)


        feature, hogimage = hog(
            image,
            orientations=9,
            pixels_per_cell=(8, 8),
            cells_per_block=(2, 2),
            block_norm="L2-Hys",
            visualize=True
        )


        images.append(image)
        features.append(feature)
        hog_images.append(hogimage)
        labels.append(class_name)


images = np.array(images)
features = np.array(features)
hog_images = np.array(hog_images)
labels = np.array(labels)

print("Images shape:")
print(images.shape)

print("\nHOG features shape:")
print(features.shape)

print("\nHOG images shape:")
print(hog_images.shape)

print("\nLabels shape:")
print(labels.shape)

print("\nNumber of classes:")
print(len(np.unique(labels)))

print("\nNumber of images:")
print(len(images))


X = features
y = labels


X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)



print("Training samples:")
print(X_train.shape)

print("Testing samples:")
print(X_test.shape)


scaler = StandardScaler()


X_train_scaled = scaler.fit_transform(
    X_train
)

X_test_scaled = scaler.transform(
    X_test
)


print("Mean:")
print(X_train_scaled.mean())

print("Std:")
print(X_train_scaled.std())


model = SVC()


param_grid = {
    "C": [
        0.01,
        0.1,
        1
    ],

    "gamma": [
        "scale",
        0.01,
        0.1
    ],

    "kernel": [
        "linear",
        "rbf"
    ]
}


grid_model = GridSearchCV(
    estimator=model,
    param_grid=param_grid,
    cv=3,
    n_jobs=-1,
    verbose=1,
    scoring="accuracy"
)


print("\n======================================")
print("TRAINING SVM")
print("======================================")


grid_model.fit(
    X_train_scaled,
    y_train
)


best_model = grid_model.best_estimator_

print("Best parameters:")
print(
    grid_model.best_params_
)

print("\nBest CV Accuracy:")
print(
    grid_model.best_score_
)


print("\nBest model:")
print(
    best_model
)


predictions = best_model.predict(
    X_test_scaled
)


accuracy = accuracy_score(
    y_test,
    predictions
)


print("Test Accuracy:")
print(
    accuracy
)


print("\nNumber of support vectors:")
print(
    len(
        best_model.support_vectors_
    )
)


