pca = PCA(
    n_components=3
)


X_pca = pca.fit_transform(
    X_train_scaled
)


print("Original feature dimension:")
print(
    X_train_scaled.shape[1]
)


print("\nPCA shape:")
print(
    X_pca.shape
)


print("\nExplained variance ratio:")
print(
    pca.explained_variance_ratio_
)


